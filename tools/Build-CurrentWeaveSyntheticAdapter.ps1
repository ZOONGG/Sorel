param(
    [string]$JavaHome = 'C:/Program Files/Java/jdk-25.0.3',
    [string]$LoaderPath = "$env:LOCALAPPDATA/Sorel/dev/cache/runtime/weave/weave-loader.jar",
    [string]$GenesisPath = "$env:USERPROFILE/.lunarclient/offline/multiver/genesis-0.1.0-SNAPSHOT-all.jar"
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$build = Join-Path $root 'runtime/current-synthetic-adapter'
$loader = $LoaderPath
$genesis = $GenesisPath
if ((Get-FileHash -LiteralPath $loader).Hash -ne '013B7B9A4CA01A473A1FFC0B031C843C70FE61616E9048FB326E03794C8457B7') { throw 'Untouched Weave 1.3.4 hash mismatch.' }
$genesisHash = (Get-FileHash -LiteralPath $genesis).Hash
$verifiedGenesis = @(
    'E3F34C4AD92F1C3BAE83C17BBACB45952C156DF359CB39D6C34D086B05E83C44',
    '40797AD1D1449FFFF7C6E7342B79A3EDC8D08517505DC2D57CE9D97E0669389C',
    'B8DC53894251BA825C0B0A899EEAC00DB8CF311C9BA02E182F8650C4887B9CFC',
    '26FE6DD9D4A6C3630ACA96C22FAF52ED6D6FA4F772D23258E1E91F8289ABB0EF',
    '23FDDB13D3255963DFBB8C3EE8A33D0A85260902DDBF8ABBFF66F016FF55B7E4'
)
if ($genesisHash -notin $verifiedGenesis) { throw 'Untouched Genesis hash mismatch.' }
$gameLoader = if ($genesisHash -in $verifiedGenesis[2..4]) {
    'com/moonsworth/lunar/genesis/HIIIRCIHHCOIRCOHOIIRRCRIHHRICI'
} else {
    'com/moonsworth/lunar/genesis/ORCOIHCCICICIHRCCCCHHHRICHHICI'
}
New-Item -ItemType Directory -Force -Path "$build/classes" | Out-Null
& "$JavaHome/bin/javac.exe" --release 17 -cp "$loader;$genesis" -d "$build/classes" (Get-ChildItem "$PSScriptRoot/current-weave-synthetic/*.java" | ForEach-Object FullName)
if ($LASTEXITCODE) { throw 'Adapter compilation failed.' }
& "$JavaHome/bin/java.exe" -Xverify:all -cp "$build/classes;$loader;$genesis" dev.sorel.current.SyntheticIntegrationTest $genesis $gameLoader
if ($LASTEXITCODE) { throw 'Synthetic integration check failed.' }
if ((Get-FileHash -LiteralPath $genesis).Hash -ne $genesisHash) { throw 'Genesis changed during verification.' }
$classNames = @('CurrentSyntheticAgent','SyntheticLoaderMethods','SyntheticLoaderAdapter','SyntheticResolver')
$lines = @('namespace Sorel.Services;', '// Generated by tools/Build-CurrentWeaveSyntheticAdapter.ps1, Java 17.', 'internal static class CurrentSyntheticAdapterClasses', '{', '    internal static readonly System.Collections.Generic.Dictionary<string, string> Bytes = new()', '    {')
foreach ($name in $classNames) {
    $bytes = [IO.File]::ReadAllBytes("$build/classes/dev/sorel/current/$name.class")
    $lines += '        ["dev/sorel/current/' + $name + '.class"] = "' + [Convert]::ToBase64String($bytes) + '",'
}
$lines += '    };', '}'
[IO.File]::WriteAllText((Join-Path $root 'src/Sorel/Services/CurrentSyntheticAdapterClasses.cs'), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Output 'Current synthetic adapter verified and embedded.'
